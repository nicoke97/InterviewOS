def translate_prompt(text: str) -> str:
    if not text:
        return text
    protected, tokens = _protect_literals(text)
    out = _apply_regexes(protected)
    out = _apply_phrases(out)
    out = _apply_regexes(out)
    out = _protect_calls(out, tokens)
    out = _apply_connectives(out)
    out = _apply_words(out)
    # Second phrase pass catches leftovers created by connectives/words
    # (e.g. "con espacio" → "with espacio" → "with a space").
    out = _apply_phrases(out)
    out = _cleanup(out)
    return _restore(out, tokens)


def translate_hints(hints: list[str]) -> list[str]:
    return [translate_prompt(h) for h in hints]


