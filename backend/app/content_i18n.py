"""ES → EN for Kumon prompts and hints.

Quoted literals, assignment targets, and ``(formato: …)`` blocks stay in the
source language so the student still prints the exact stdout the validator
expects. Only instructional wording is translated.
"""
from __future__ import annotations

import re

_TOKEN = re.compile(r"\uE000(\d+)\uE001")

# ---------------------------------------------------------------------------
# protect / restore
# ---------------------------------------------------------------------------

def _stash(tokens: list[str], value: str) -> str:
    tokens.append(value)
    return f"\uE000{len(tokens) - 1}\uE001"


def _protect_literals(text: str) -> tuple[str, list[str]]:
    """Hide quotes, formato blocks, print templates, and assignments.

    Function calls stay visible so phrase tables that mention ``print()`` or
    ``O(1)`` can still match. Calls are stashed later, before word replacement,
    so identifiers like ``mayúscula()`` are not translated.
    """
    tokens: list[str] = []

    def stash_m(match: re.Match[str]) -> str:
        return _stash(tokens, match.group(0))

    def formato_m(match: re.Match[str]) -> str:
        return "(exact format: " + _stash(tokens, match.group(1).strip()) + ")"

    out = re.sub(r"\(formato:\s*([^)]*)\)", formato_m, text)
    out = re.sub(r"'(?:\\.|[^'\\])*'", stash_m, out)
    out = re.sub(r'"(?:\\.|[^"\\])*"', stash_m, out)
    # Keep required print templates like '<titulo> [<estado>]'
    out = re.sub(r"<[^>\s]+>(?:\s*<[^>\s]+>)*", stash_m, out)
    out = re.sub(r"\b[A-Za-z_]\w*\s*=", stash_m, out)
    return out, tokens


def _protect_calls(text: str, tokens: list[str]) -> str:
    def stash_m(match: re.Match[str]) -> str:
        return _stash(tokens, match.group(0))

    return re.sub(r"\b[A-Za-z_]\w*\(", stash_m, text)


def _restore(text: str, tokens: list[str]) -> str:
    def repl(match: re.Match[str]) -> str:
        idx = int(match.group(1))
        return tokens[idx] if 0 <= idx < len(tokens) else match.group(0)

    return _TOKEN.sub(repl, text)


