def pick(tree: dict, idx: int) -> dict:
    out: dict = {}
    for k, v in tree.items():
        if isinstance(v, dict) and v and isinstance(next(iter(v.values())), list):
            out[k] = pick(v, idx)
        elif isinstance(v, list) and len(v) == 2:
            out[k] = v[idx]
        else:
            out[k] = v
    return out


def to_ts(name: str, data: dict) -> str:
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return f"import type {{ Messages }} from './types';\n\nexport const {name}: Messages = {body};\n"


