def _mc(sid: str, n: int, q: str, q_es: str, choices: list[str], choices_es: list[str], answer: int = 0) -> dict:
    return {
        "id": f"{sid}-q{n}",
        "q": q,
        "q_es": q_es,
        "choices": choices,
        "choices_es": choices_es,
        "answer": answer,
    }


def _fc(sid: str, n: int, front: str, front_es: str, back: str, back_es: str) -> dict:
    return {
        "id": f"{sid}-c{n}",
        "front": front,
        "front_es": front_es,
        "back": back,
        "back_es": back_es,
    }


