    idx = 0
    for sec in foundation_sections():
        sec["index"] = idx
        sections.append(sec)
        idx += 1
    for week_id, week_en, week_es, anchor_en, anchor_es, days in WEEKS:
        for i, (title_en, title_es, reading_en, reading_es) in enumerate(days, start=1):
            idx += 1
            sid = f"{week_id}-s{i}"
            hand = HAND_CARDS.get((week_id, i))
            if hand:
                cards = [{"id": f"{sid}-c{n}", **c} for n, c in enumerate(hand, start=1)]
